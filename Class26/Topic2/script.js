// Q1: push() add 3
let arr1 = [1, 2];
arr1.push(3);

console.log("Q1:", arr1);

// Q2: pop() remove last element
let arr2 = [10, 20, 30];

let removedValue1 = arr2.pop();

console.log("Q2 Updated Array:", arr2);
console.log("Q2 Removed Value:", removedValue1);

// Q3: unshift() add at beginning
let arr3 = [2, 3];

arr3.unshift(1);

console.log("Q3:", arr3);

// Q4: shift() remove first element
let arr4 = [1, 2, 3];

let removedValue2 = arr4.shift();

console.log("Q4 Updated Array:", arr4);
console.log("Q4 Removed Value:", removedValue2);

// Q5: push() multiple elements
let arr5 = [1, 2, 3];

arr5.push(4, 5);

console.log("Q5:", arr5);

// Q6: unshift() multiple elements
let arr6 = [3, 4];

arr6.unshift(1, 2);

console.log("Q6:", arr6);

// Q7: pop() remove last name
let names = ["Rahul", "Amit", "Raj"];

let removedName = names.pop();

console.log("Q7 Updated Array:", names);
console.log("Q7 Removed Name:", removedName);

